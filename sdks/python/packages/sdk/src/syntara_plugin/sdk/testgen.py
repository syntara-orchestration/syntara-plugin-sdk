"""Deterministic pytest scaffolding for custom-workload Action steps.

The generator compiles the workspace through the same canonical compiler the
``validate`` command uses, then emits one test module per custom-workload
Action target. The generated file is the checklist: valid input reaches the
business hook once, every invalid case blocks it, and the direct and
container-adapter paths yield equivalent outcomes. Generated code imports the
``syntara-plugin-testing`` package; this module never imports it, so the sdk
package keeps no dependency on the testing package.

A generated suite never fails on first run. Business-independent tests (the
derived invalid-input cases) run immediately; the valid-input and equivalence
tests are skipped until the author replaces the scaffolded placeholder with a
business-valid payload, because only the implementation's business rules can
make a schema-valid placeholder business-valid. The scaffolded case is also
validated against the compiled input schema, and any schema errors are
quoted in the skip marker's TODO when no placeholder can satisfy them.
"""

from __future__ import annotations

import os
import re
from collections.abc import Mapping
from pathlib import Path
from typing import Any

from jsonschema import Draft202012Validator, FormatChecker

from .authoring import BuildRequest, compile_workspace

_MAX_INVALID_CASES = 8
_IDENTIFIER_SAFE = re.compile(r"[^a-z0-9]")

_TEMPLATE = '''"""Generated local tests for the {identity} Action step.

Regenerate with: syntara-plugin test-init {manifest} --force
Review the TODO markers and extend the cases with business-specific payloads.
"""

from __future__ import annotations

from pathlib import Path

import pytest

from syntara_plugin.testing import (
    assert_outcomes_equivalent,
    invoke_step,
    invoke_step_in_container,
)

ENTRY_POINT = "{entry_point}"
WORKSPACE = (Path(__file__).resolve().parent / {workspace_relative!r}).resolve()

VALID_CASES = [
{valid_cases}
]

INVALID_CASES = [
{invalid_cases}
]


{valid_guard}def test_valid_input_reaches_the_hook_once(mock_execution_context, step_bindings):
    binding = step_bindings.bind_action(ENTRY_POINT, workspace=WORKSPACE)
    outcome = invoke_step(binding, VALID_CASES[0], context=mock_execution_context())
    assert outcome.ok, outcome.error
    assert outcome.run_calls == 1


{invalid_guard}def test_invalid_input_blocks_the_hook(mock_execution_context, step_bindings):
    binding = step_bindings.bind_action(ENTRY_POINT, workspace=WORKSPACE)
    for inputs in INVALID_CASES:
        outcome = invoke_step(binding, inputs, context=mock_execution_context())
        assert not outcome.ok, inputs
        assert outcome.run_calls == 0, inputs


{valid_guard}def test_direct_and_container_paths_are_equivalent(mock_execution_context, step_bindings):
    binding = step_bindings.bind_action(ENTRY_POINT, workspace=WORKSPACE)
    context = mock_execution_context(invocation_id="generated-equivalence")
    direct = invoke_step(binding, VALID_CASES[0], context=context)
    container = invoke_step_in_container(binding, VALID_CASES[0], context=context)
    assert_outcomes_equivalent(direct, container)


# TODO: add a schema-invalid output case once the implementation can emit one.
# TODO: add a deliberate-failure case once the implementation signals failure.
# TODO: assert secrets never leak (assert_no_secrets + secret_sentinel) once
#       the input declares credential-like fields.
'''

_CONTEST_TEMPLATE = '''"""Generated by syntara-plugin test-init: make the workspace importable."""

from __future__ import annotations

import sys
from pathlib import Path

sys.path.insert(0, str((Path(__file__).resolve().parent / {workspace_relative!r}).resolve()))
'''

_VALID_SKIP = '''# TODO: replace the scaffolded VALID_CASES with a business-valid payload,
# then remove this skip. The placeholder is schema-valid, but only the
# implementation's business rules can make it business-valid.
{schema_note}
@pytest.mark.skip(reason="scaffolded placeholder; replace VALID_CASES with a business-valid payload")
'''

_SKIP_NO_INVALID = '''# TODO: no invalid case could be derived from the declared input schema
# (nothing is required, enum-constrained, or singly typed); add
# business-specific invalid payloads to INVALID_CASES.
@pytest.mark.skip(reason="no invalid case could be derived from the input schema")
'''


class ScaffoldError(ValueError):
    """Raised when test scaffolding cannot be generated safely."""


def generate_step_tests(
    root_manifest: Path,
    *,
    tests_dir: Path | None = None,
    force: bool = False,
) -> list[Path]:
    """Generate pytest modules for every custom-workload Action target.

    Returns the written paths. Existing files are only replaced when ``force``
    is true; the ``tests/conftest.py`` import shim is written only when absent
    so author-owned conftest content is never overwritten.
    """

    manifest = _resolve_manifest(root_manifest)
    result = compile_workspace(
        BuildRequest(root_manifest=manifest, require_image_bindings=False)
    )
    workspace = manifest.parent
    tests = _resolve_tests_dir(workspace, tests_dir)
    workspace_relative = os.path.relpath(workspace, tests)
    planned = _plan_test_modules(result, tests, manifest.name, workspace_relative)
    if not planned:
        message = "the workspace declares no custom-workload Action targets"
        raise ScaffoldError(message)
    _refuse_existing(planned, force)
    written = _write_planned_modules(planned)
    written.extend(_write_conftest(tests, workspace_relative))
    return written


def _resolve_manifest(root_manifest: Path) -> Path:
    """Resolve the root manifest, rejecting traversal in the supplied path."""

    manifest = Path(root_manifest).expanduser()
    if ".." in manifest.parts:
        message = f"manifest path must not contain '..' path traversal: {root_manifest}"
        raise ScaffoldError(message)
    if manifest.is_dir():
        manifest = manifest / "plugin.yaml"
    if not manifest.is_file():
        message = f"plugin manifest not found: {manifest}"
        raise ScaffoldError(message)
    return manifest


def _resolve_tests_dir(workspace: Path, tests_dir: Path | None) -> Path:
    """Resolve the tests directory against the workspace, rejecting traversal."""

    if tests_dir is None:
        return workspace / "tests"
    resolved = tests_dir.expanduser()
    if ".." in resolved.parts:
        message = f"tests directory must not contain '..' path traversal: {tests_dir}"
        raise ScaffoldError(message)
    # A relative --tests-dir resolves against the workspace, never the current
    # directory; the default is already workspace-relative.
    return resolved if resolved.is_absolute() else workspace / resolved


def _plan_test_modules(
    result: Any,
    tests: Path,
    manifest_name: str,
    workspace_relative: str,
) -> list[tuple[Path, str]]:
    """Plan every module before writing so a mid-run overwrite refusal never
    leaves a half-generated suite behind."""

    planned: list[tuple[Path, str]] = []
    for target in result.descriptor["spec"]["targets"]:
        runtime = target.get("runtime", {})
        if target.get("kind") != "Action" or runtime.get("kind") != "custom-workload":
            continue
        entry_point = str(runtime["entryPoint"])
        valid, invalid, valid_errors = _cases_from_schema(target["input"])
        path = tests / f"test_{_slug(str(target['metadata']['name']))}.py"
        planned.append(
            (
                path,
                _TEMPLATE.format(
                    identity=target["identity"],
                    manifest=manifest_name,
                    entry_point=entry_point,
                    workspace_relative=workspace_relative,
                    valid_cases=_render_cases([valid]),
                    invalid_cases=_render_cases(invalid),
                    valid_guard=_skip_guard(valid_errors),
                    invalid_guard="" if invalid else _SKIP_NO_INVALID,
                ),
            )
        )
    return planned


def _refuse_existing(planned: list[tuple[Path, str]], force: bool) -> None:
    """Refuse to replace planned files unless ``force`` was requested."""

    if force:
        return
    existing = [path for path, _ in planned if path.exists()]
    if existing:
        listed = ", ".join(str(path) for path in existing)
        message = f"refusing to overwrite existing file(s): {listed} (use --force)"
        raise ScaffoldError(message)


def _write_planned_modules(planned: list[tuple[Path, str]]) -> list[Path]:
    """Write every planned module and return the written paths."""

    written: list[Path] = []
    for path, content in planned:
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(path)
    return written


def _write_conftest(tests: Path, workspace_relative: str) -> list[Path]:
    """Write the import shim only when the author has none."""

    conftest = tests / "conftest.py"
    if conftest.exists():
        return []
    conftest.write_text(
        _CONTEST_TEMPLATE.format(workspace_relative=workspace_relative),
        encoding="utf-8",
    )
    return [conftest]


def _slug(name: str) -> str:
    """Turn one target name into a stable lowercase underscore test-file slug."""

    slug = _IDENTIFIER_SAFE.sub("_", name.lower()).strip("_")
    return slug or "step"


def _render_cases(cases: list[dict[str, Any]]) -> str:
    rendered = "\n".join(f"    {case!r}," for case in cases)
    return rendered or "    {},"


def _skip_guard(valid_errors: list[str]) -> str:
    """Render the replace-me skip marker for the placeholder-dependent tests.

    The marker is always emitted: a schema-valid placeholder can still violate
    business invariants, so the valid-input and equivalence tests stay skipped
    until the author supplies a business-valid payload. Schema errors, when
    present, are quoted in the TODO.
    """

    schema_note = ""
    if valid_errors:
        lines = "\n".join(f"#   {error}" for error in valid_errors)
        schema_note = (
            "# The placeholder also fails the declared input schema; schema\n"
            "# validation reported:\n" + lines
        )
    return _VALID_SKIP.format(schema_note=schema_note)


def _cases_from_schema(
    schema: Mapping[str, Any],
) -> tuple[dict[str, Any], list[dict[str, Any]], list[str]]:
    """Derive one valid case and bounded invalid cases from an input schema.

    Returns the valid case, the invalid cases, and the schema-validation errors
    for the valid case (empty when the scaffolded placeholder satisfies the
    declared constraints). Derived invalid cases that the schema actually
    accepts (for example a wrong-typed value under a union type) are dropped,
    so the generated invalid test only iterates cases that genuinely fail.
    """

    properties = schema.get("properties", {})
    if not isinstance(properties, Mapping):
        properties = {}
    required = [field for field in schema.get("required", []) if isinstance(field, str)]
    valid = {
        field: _placeholder(field, properties.get(field, {})) for field in required
    }
    valid_errors = _validate_case(schema, valid)
    invalid: list[dict[str, Any]] = []
    for field in required:
        case = {key: value for key, value in valid.items() if key != field}
        invalid.append(case)
    for field, property_schema in properties.items():
        if not isinstance(property_schema, Mapping):
            continue
        if "enum" in property_schema:
            invalid.append({**valid, field: _non_enum_value(field, property_schema)})
        elif field in required:
            wrong = _wrong_typed_value(property_schema)
            if wrong is not _UNSET:
                invalid.append({**valid, field: wrong})
        if len(invalid) >= _MAX_INVALID_CASES:
            break
    kept = [case for case in invalid[:_MAX_INVALID_CASES] if _validate_case(schema, case)]
    return valid, kept, valid_errors


def _validate_case(schema: Mapping[str, Any], case: Mapping[str, Any]) -> list[str]:
    """Return the schema-validation errors for one scaffolded case."""

    if not isinstance(schema, Mapping) or not schema:
        return []
    try:
        validator = Draft202012Validator(schema, format_checker=FormatChecker())
        errors = sorted(validator.iter_errors(case), key=lambda error: list(error.path))
    except Exception:  # noqa: BLE001 - an unvalidatable schema must not break scaffolding
        return []
    return [f"{list(error.path)}: {error.message}" for error in errors]


_UNSET = object()

_FORMAT_PLACEHOLDERS: dict[str, str] = {
    "date-time": "2026-01-01T12:00:00Z",
    "date": "2026-01-01",
    "time": "12:00:00Z",
    "duration": "P1D",
    "uuid": "123e4567-e89b-42d3-a456-426614174000",
    "email": "example@example.test",
    "idn-email": "example@example.test",
    "uri": "https://example.test/",
    "uri-reference": "/example",
    "iri": "https://example.test/",
    "hostname": "example.test",
    "idn-hostname": "example.test",
    "ipv4": "192.0.2.1",
    "ipv6": "2001:db8::1",
    "json-pointer": "/example",
    "regex": "example",
}


def _placeholder(field: str, property_schema: Mapping[str, Any]) -> Any:
    """Pick one deterministic, schema-valid placeholder value for a field."""

    if "default" in property_schema:
        return property_schema["default"]
    if "enum" in property_schema and isinstance(property_schema["enum"], list):
        return property_schema["enum"][0]
    declared_format = property_schema.get("format")
    if isinstance(declared_format, str) and declared_format in _FORMAT_PLACEHOLDERS:
        return _fit_bounds(_FORMAT_PLACEHOLDERS[declared_format], property_schema)
    schema_type = property_schema.get("type")
    if schema_type == "integer":
        return 1
    if schema_type == "number":
        return 1.5
    if schema_type == "boolean":
        return True
    if schema_type == "array":
        return []
    if schema_type == "object":
        return {}
    return _fit_bounds(f"example-{field}", property_schema)


def _fit_bounds(value: str, property_schema: Mapping[str, Any]) -> str:
    """Fit one string placeholder inside declared length bounds when possible."""

    minimum = property_schema.get("minLength")
    maximum = property_schema.get("maxLength")
    if not isinstance(minimum, int) and not isinstance(maximum, int):
        return value
    if isinstance(maximum, int) and len(value) > maximum:
        value = value[:maximum]
    if isinstance(minimum, int) and len(value) < minimum:
        value = value + "x" * (minimum - len(value))
    return value


def _non_enum_value(field: str, property_schema: Mapping[str, Any]) -> str:
    """Return one deterministic value guaranteed outside the declared enum."""

    values = property_schema.get("enum", [])
    candidate = f"invalid-{field}"
    while candidate in values:
        candidate = f"{candidate}-x"
    return candidate


def _wrong_typed_value(property_schema: Mapping[str, Any]) -> Any:
    """Return one value of the wrong type for a typed field."""

    schema_type = property_schema.get("type")
    if schema_type == "integer" or schema_type == "number":
        return "not-a-number"
    if schema_type == "boolean":
        return "not-a-boolean"
    if schema_type == "array":
        return "not-a-list"
    if schema_type == "object":
        return "not-an-object"
    return 12345
